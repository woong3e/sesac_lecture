# CoT는 모델에게 답만 바로 말하지 말고 풀이 과정을 단계별로 적은 뒤 답을 내게 하는 기법이에요. 
# 계산이나 조건이 여러 개인 문제처럼 여러 단계를 거쳐야 하는 문제에서 효과가 있어요.
# 왜 효과가 있나
# LLM은 텍스트를 앞에서부터 한 토큰(글자 조각)씩 이어서 만들어요. 
# 답을 바로 내라고 하면 중간 계산 없이 한 번에 찍어야 해서 틀리기 쉬워요. 
# 과정을 먼저 쓰게 하면 그 중간 결과를 보면서 다음 단계를 이어 갈 수 있어서 정확도가 올라가요. 
# 사람이 암산하지 않고 연습장에 풀어 보는 것과 비슷해요.

from lesson_support import lesson_client, show_prompt

PROBLEM = """내 차를 세차하고 싶다.
세차장은 50미터 거리에 있다.
걸어가야 하는가, 아니면 운전해서 가야 하는가?"""

def main():
    with lesson_client() as client:
        show_prompt(client, "짧은 답 요청",f"{PROBLEM}\n한 문장으로 답하세요.")
        show_prompt(client, "필요 조건과 짧은 근거 요청",
                    f"{PROBLEM}\n 이동해야 할 대상이 무엇인지 고려해서 결론과 근거를 각각 한 문장으로 답하세요.")

if __name__ == "__main__":
    main()